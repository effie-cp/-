def grid(ws, r0, r1, c0, c1, label_cols=2):
    for rr in range(r0, r1):
        for cc in range(c0, c1):
            cell = ws.cell(row=rr, column=cc)
            cell.font = BOLD if cc <= label_cols else BLACK
            cell.alignment = WRAP; cell.border = BOX

